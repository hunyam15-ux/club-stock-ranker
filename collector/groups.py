def is_holdco(r: dict) -> bool:
    if r.get("is_financial"):
        return False  # 금융지주는 은행·증권 업종끼리 비교하는 게 맞다
    name = r.get("name") or ""
    text = " ".join(r.get("summary") or [])[:400]
    if _NOT_HOLD_RE.search(text):
        return False
    if name.endswith("홀딩스") or name.endswith("지주"):
        return True
    return bool(_HOLD_RE.search(text))


def group_of(name: str | None) -> str:
    n = (name or "").strip()
    base = re.sub(r"(우|우B|2우B|3우B)$", "", n)
    if base in _HYUNDAI_MOTOR:
        return "현대차"
    for pre, g in _PREFIX:
        if base.startswith(pre):
            return g
    return base or n
